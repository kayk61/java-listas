package java_lista_8;

import java.util.Scanner;

public class at1 {
    public static void main(String[] args) {
        //1. Contar de 1 a 10
        //Exiba os números de 1 até 10 utilizando o comando Para.
        Scanner sc=new Scanner(System.in);

        for (int n=0;n<=10;n++) {
            System.out.println(n);
        }
        sc.close();
    }
}
